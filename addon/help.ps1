Add-Type -AssemblyName Microsoft.VisualBasic
$msg = @"
DSH 桥怎么用

1) 启动服务
   双击脚本目录里的「启动WPS桥.bat」，会弹出一个 PowerShell 窗口，
   底部显示手机要用的地址。那个窗口不能关，关了服务就停了。可以最小化。
   （功能区里不再放「启动服务」按钮：WPS 的安全策略会拦它起进程，
   点了只会弹一个 cmd.exe 风险警告。）

2) 换端口 / 换脚本位置
   点「端口 / 路径」，三个输入框依次问：端口、脚本路径、是否允许脚本。
   改完要关掉桥的窗口、重新双击「启动WPS桥.bat」才生效。

3) 手机那边怎么连
   点「手机命令」，会弹出完整命令并复制到剪贴板，
   粘到手机终端里执行一次就行。校园网换 IP 后重新点一次。

4) 探活
   点「探活」，能看到 HTTP 200 和主机名就说明通了。

5) 常见问题
   - 服务窗口一闪就没：端口被占用，换个端口。
   - 手机连不上：电脑网络是「公用」时防火墙会挡，脚本会自动加规则。
"@
[Microsoft.VisualBasic.Interaction]::MsgBox($msg, 'OKOnly,Information', 'DSH 桥')
